// Run against a server with no environment keys. No paid calls: provider requests are intercepted below.
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const { expect } = require('playwright/test')
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || undefined })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  // This test cannot spend tokens, even against a configured app.
  await page.route('**/api/message', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ code: 'missing_key', error: 'Add an API key in Model settings.', retryable: false }) }))
  await page.goto(process.argv[2] || 'http://127.0.0.1:5275')
  await page.waitForLoadState('networkidle')
  await page.getByText('Model settings', { exact: false }).first().click({ timeout: 3000 })
  await expect(page.getByLabel('Provider', { exact: true })).toBeVisible()
  await page.getByLabel('Provider', { exact: true }).selectOption('openai')
  const keyInput = page.getByLabel('Session API key', { exact: true })
  await expect(keyInput).toHaveAttribute('placeholder', 'Enter your provider API key')
  await page.getByLabel('Session API key', { exact: true }).fill('synthetic-smoke-test-key')
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Settings saved')
  await expect(keyInput).toHaveValue('')
  await expect(keyInput).toHaveAttribute('placeholder', /^\*+$/)
  await expect(keyInput).toHaveAccessibleDescription(/Key configured/)
  await expect(page.getByRole('button', { name: 'Forget session key', exact: true })).toBeVisible()
  if (process.argv[3]) await page.screenshot({ path: process.argv[3], fullPage: true })
  if ((await page.evaluate(() => JSON.stringify([localStorage, sessionStorage]))).includes('synthetic-smoke-test-key')) throw new Error('API key leaked into browser storage')
  // Display-only asterisks must never be sent back as a replacement key.
  const unchangedKeySave = page.waitForRequest(request => request.url().endsWith('/api/settings') && request.method() === 'POST')
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  expect((await unchangedKeySave).postDataJSON()).not.toHaveProperty('apiKey')
  await expect(page.getByRole('status')).toContainText('Settings saved')
  await expect(keyInput).toHaveAttribute('placeholder', /^\*+$/)
  // Each provider has its own key status, not the previously selected provider's.
  await page.getByLabel('Provider', { exact: true }).selectOption('anthropic')
  await expect(keyInput).toHaveAttribute('placeholder', 'Enter your provider API key')
  await expect(keyInput).not.toHaveAccessibleDescription(/Key configured/)
  await page.getByLabel('Provider', { exact: true }).selectOption('openai')
  await expect(keyInput).toHaveAttribute('placeholder', /^\*+$/)
  await expect(page.getByLabel('Model ID', { exact: true })).toHaveAttribute('placeholder', 'gpt-6-astra')
  await page.reload()
  await page.waitForLoadState('networkidle')
  await page.getByText('Model settings', { exact: false }).first().click()
  await expect(page.getByLabel('Provider', { exact: true })).toHaveValue('openai')
  await expect(page.getByLabel('Session API key', { exact: true })).toHaveValue('')
  await expect(keyInput).toHaveAttribute('placeholder', /^\*+$/)
  await expect(keyInput).toHaveAccessibleDescription(/Key configured/)
  await page.getByRole('button', { name: 'Forget session key', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Forget session key', exact: true })).not.toBeVisible()
  await expect(keyInput).toHaveAttribute('placeholder', 'Enter your provider API key')
  await expect(keyInput).not.toHaveAccessibleDescription(/Key configured/)
  await page.getByRole('button', { name: 'Close model settings' }).click()
  await page.getByRole('button', { name: 'Browse templates', exact: true }).click()
  await page.locator('[data-template-generator="rockCluster"]').click()
  await expect(page.getByRole('button', { name: 'Save to Library', exact: true })).toBeEnabled()
  await expect(page.getByText('Add an API key in Model settings.', { exact: true })).not.toBeVisible()
  await page.getByPlaceholder('Describe what you want to create...').fill('A cluster of mossy rocks')
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(page.getByText('Add an API key in Model settings.', { exact: true })).toBeVisible()
  await page.route('**/api/message', async route => {
    await new Promise(resolve => setTimeout(resolve, 2000))
    await route.abort().catch(() => {})
  })
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel request', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Cancel request', exact: true })).not.toBeVisible()
  await page.route('**/api/message', async route => {
    const request = route.request().postDataJSON()
    if (request.task === 'creative') {
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify({
        text: 'function createAsset(THREE, seed, textures, params, addons) { const root = new THREE.Group(); root.add(new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1), new THREE.MeshStandardMaterial())); return { root }; }',
        provider: 'openai', model: 'gpt-6-astra', usage: {}
      }) })
    }
    await new Promise(resolve => setTimeout(resolve, 2000))
    await route.abort().catch(() => {})
  })
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await page.getByTitle('Edit with AI', { exact: true }).click()
  await page.getByLabel("What would you like to change?").fill('Make it blue')
  await page.getByRole('button', { name: 'Apply Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel edit request', exact: true }).click({ timeout: 3000 })
  await expect(page.getByRole('heading', { name: 'Generative Edit', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Generate', exact: true })).toBeEnabled()
  let expiredRequests = 0
  await page.route('**/api/message', route => {
    expiredRequests++
    return route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ code: 'session_expired', error: 'Local session expired.', retryable: false }) })
  })
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  const reconnectAlert = page.getByRole('alert').filter({ has: page.getByRole('button', { name: 'Reconnect', exact: true }) })
  await expect(reconnectAlert).toBeVisible()
  await page.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate', exact: true })).toBeEnabled()
  if (expiredRequests !== 1) throw new Error('Generation retried after session expiry without confirmation')
  await page.getByRole('button', { name: 'Reconnect', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Model settings' }).getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect(reconnectAlert).toHaveCount(0)
  console.log('Provider settings, key lifecycle, session reconfirmation, templates, API errors and edit cancellation: passed')
} finally {
  await browser.close()
}
