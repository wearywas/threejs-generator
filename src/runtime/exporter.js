/**
 * Generate a portable code snippet for Creative/Procedural mode assets
 * Includes necessary addon imports and setup code
 * @param {string} code - The generated createAsset function code
 * @param {string[]} usedAddons - Array of addon names used
 * @param {object} options - Additional options
 * @returns {string} - Complete portable code
 */
export function generateCreativeCodeSnippet(code, usedAddons = [], options = {}) {
  const { seed = 12345, hasAnimation = false } = options
  
  // Generate addon imports
  const addonImports = generateAddonImports(usedAddons)
  
  // Generate addon setup code if needed
  let addonSetup = ''
  if (usedAddons.length > 0) {
    addonSetup = `
// Setup addons object (replicate the runtime environment)
const addons = {
  ${usedAddons.includes('Water') ? 'Water,' : ''}
  ${usedAddons.includes('Water2') ? 'Water2,' : ''}
  ${usedAddons.includes('Sky') ? 'Sky,' : ''}
  ${usedAddons.includes('Reflector') ? 'Reflector,' : ''}
  ${usedAddons.includes('SimplexNoise') ? 'SimplexNoise,' : ''}
  textures: {
    // You may need to create a water normals texture
    // See: https://threejs.org/examples/#webgl_shaders_ocean
    waterNormals: null // Replace with your water normals texture
  }
};
`.trim()
  }

  // Build the complete snippet
  let snippet = `// Creative Mode Asset
// Generated by ThreeJS Generator
// ${usedAddons.length > 0 ? `Uses addons: ${usedAddons.join(', ')}` : 'No addons required'}

import * as THREE from 'three';
${addonImports}
${addonSetup}

// Generated asset factory
${code}

// Usage example:
const seed = ${seed};
const textures = {}; // Add any textures here
const params = {};   // Add any parameter overrides here
${usedAddons.length > 0 ? '' : '// const addons = null; // No addons needed'}

const asset = createAsset(THREE, seed, textures, params${usedAddons.length > 0 ? ', addons' : ''});

// Add to your scene
scene.add(asset.root);
`

  if (hasAnimation) {
    snippet += `
// Animation loop (asset has runtime animation)
const clock = new THREE.Clock();
function animate() {
  requestAnimationFrame(animate);
  const delta = clock.getDelta();
  const elapsed = clock.getElapsedTime();
  
  // Update asset animation
  if (asset.update) {
    asset.update(elapsed, delta);
  }
  
  renderer.render(scene, camera);
}
animate();
`
  }

  snippet += `
// Cleanup when done:
// asset.dispose();
`

  return snippet
}

/**
 * Generate minimal code for clipboard copy (just the function)
 * @param {string} code - The createAsset function code
 * @param {string[]} usedAddons - Array of addon names used  
 * @returns {string}
 */
export function generateMinimalCodeSnippet(code, usedAddons = []) {
  let header = '// ThreeJS Generator - Creative Mode Asset\n'
  
  if (usedAddons.length > 0) {
    header += `// Required addon imports:\n`
    usedAddons.forEach(addon => {
      if (ADDON_IMPORTS[addon]) {
        header += `// ${ADDON_IMPORTS[addon]}\n`
      }
    })
    header += '\n'
  }
  
  return header + code
}

