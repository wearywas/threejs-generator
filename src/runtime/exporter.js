/**
 * Generate an Instance Specification from createAsset code
 * This format enables batching for minimal draw calls when used in a world generator
 * 
 * @param {string} code - The createAsset function code
 * @param {Object} options - Generation options
 * @param {string} options.name - Name for the asset
 * @param {string} options.prompt - Original prompt used to generate the asset
 * @param {number} options.seed - Seed used for generation
 * @param {Object} options.params - Parameters used
 * @returns {Promise<Object>} - The instance specification
 */
export async function generateInstanceSpecFromCode(code, options = {}) {
  return generateSpec(code, options)
}

/**
 * Check if code can be converted to an instance specification
 * @param {string} code - The createAsset function code
 * @returns {{ valid: boolean, reason: string, recommendation?: string }}
 */
export function checkBatchingSupport(code) {
  return canConvertToInstanceSpec(code)
}

/**
 * Estimate draw call savings from batching
 * @param {Object} spec - The instance specification
 * @param {number} placementCount - Expected number of placements in world
 * @returns {{ batched: number, unbatched: number, savings: string }}
 */
export function estimateBatchingSavings(spec, placementCount = 100) {
  const { batched, unbatched } = estimateDrawCalls(spec, placementCount)
  const savingsPercent = ((unbatched - batched) / unbatched * 100).toFixed(1)
  
  return {
    batched,
    unbatched,
    savings: `${savingsPercent}% reduction (${unbatched} -> ${batched} draw calls)`
  }
}

