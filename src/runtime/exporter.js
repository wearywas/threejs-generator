/**
 * Map of addon names to their import paths
 */
const ADDON_IMPORTS = {
  Water: "import { Water } from 'three/examples/jsm/objects/Water.js'",
  Water2: "import { Water as Water2 } from 'three/examples/jsm/objects/Water2.js'",
  Sky: "import { Sky } from 'three/examples/jsm/objects/Sky.js'",
  Reflector: "import { Reflector } from 'three/examples/jsm/objects/Reflector.js'",
  SimplexNoise: "import { SimplexNoise } from 'three/examples/jsm/math/SimplexNoise.js'"
}

/**
 * Detect which addons are used in the code
 * @param {string} code - The generated code
 * @returns {string[]} - Array of addon names used
 */
export function detectUsedAddons(code) {
  const used = []
  
  // Check for direct addon class usage
  if (/\baddons\.Water\b/.test(code) && !/\baddons\.Water2\b/.test(code.split('addons.Water2').join(''))) {
    used.push('Water')
  }
  if (/\baddons\.Water2\b/.test(code)) {
    used.push('Water2')
  }
  if (/\baddons\.Sky\b/.test(code)) {
    used.push('Sky')
  }
  if (/\baddons\.Reflector\b/.test(code)) {
    used.push('Reflector')
  }
  if (/\baddons\.SimplexNoise\b/.test(code)) {
    used.push('SimplexNoise')
  }
  
  // Check for helper functions that use specific addons
  if (/\baddons\.createSkyWithSun\b/.test(code) && !used.includes('Sky')) {
    used.push('Sky')
  }
  if (/\baddons\.createWaterPlane\b/.test(code) && !used.includes('Water')) {
    used.push('Water')
  }
  
  return [...new Set(used)]
}

/**
 * Generate import statements for used addons
 * @param {string[]} usedAddons - Array of addon names
 * @returns {string} - Import statements
 */
export function generateAddonImports(usedAddons) {
  if (!usedAddons || usedAddons.length === 0) {
    return ''
  }
  
  const imports = usedAddons
    .filter(addon => ADDON_IMPORTS[addon])
    .map(addon => ADDON_IMPORTS[addon])
  
  return imports.join('\n')
}

/**
 * Export a THREE.Object3D as a GLB file
 * @param {THREE.Object3D} object - The object to export
 * @param {string} filename - Base filename (without extension)
 */
export async function exportAsGLB(object, filename = 'asset') {
  downloadGLB(await createGLB(object), filename)
}

/**
 * Export a THREE.Object3D as a GLB with animations
 * @param {THREE.Object3D} object - The object to export
 * @param {THREE.AnimationClip[]} clips - Animation clips to include
 * @param {string} filename - Base filename
 */
export async function exportAsAnimatedGLB(object, clips, filename = 'asset') {
  downloadGLB(await createGLB(object, { animations: clips }), filename)
}

export function downloadGLB(gltf, filename) {
  const url = URL.createObjectURL(new Blob([gltf], { type: 'application/octet-stream' }))
  try {
    const link = document.createElement('a')
    link.href = url
    link.download = `${filename}.glb`
    link.click()
  } finally {
    URL.revokeObjectURL(url)
  }
}

/**
 * Generate a code snippet for instantiating the asset
 * @param {Object} spec - The asset specification
 * @returns {string}
 */
export function generateCodeSnippet(spec) {
  const specJson = JSON.stringify(spec, null, 2)
  
  return `// Asset generated by ThreeJS Generator
// Generator: ${spec.generator}
// Seed: ${spec.seed}

import { createAsset } from 'threejs-generator/runtime';

// Asset specification
const spec = ${specJson};

// Create the asset
const asset = createAsset(spec);

// Add to your scene
scene.add(asset.root);

// If the asset has animations, call tick in your render loop:
if (asset.tick) {
  function animate() {
    requestAnimationFrame(animate);
    const delta = clock.getDelta();
    const elapsed = clock.getElapsedTime();
    asset.tick(elapsed, delta);
    renderer.render(scene, camera);
  }
  animate();
}

// Remember to dispose when done:
// asset.dispose();
`
}

