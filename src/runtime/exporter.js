/**
 * Generate a complete batchable export package
 * Includes both the instance spec and the original code for fallback
 * @param {string} code - The createAsset function code
 * @param {Object} options - Export options
 * @returns {Promise<string>} - Combined export content
 */
export async function generateBatchableExport(code, options = {}) {
  const {
    name = 'Batchable Asset',
    prompt = '',
    seed = 12345,
    params = {},
    textures = {}
  } = options
  
  // Generate the instance specification
  const spec = options.instanceSpec
    ? validateAnalysis(options.instanceSpec)
    : await generateSpec(code, { name, prompt, seed, params, textures })
  
  // Create combined export with both spec and original code
  const exportContent = `/**
 * Batchable Asset Export
 * Generated by ThreeJS Generator
 * 
 * This file contains both:
 * 1. Instance Specification (for batched rendering)
 * 2. Original createAsset code (for standalone use)
 * 
 * Usage in World Generator:
 *   import spec from './asset.batchable.js'
 *   batchedRenderer.addFromSpec(spec.instanceSpec, positions)
 * 
 * Standalone usage:
 *   import { createAsset } from './asset.batchable.js'
 *   const asset = createAsset(THREE, seed, textures, params)
 */

// Instance Specification for batched rendering
export const instanceSpec = ${JSON.stringify(spec, null, 2)};

// Original createAsset function for standalone use
${code}

// Export both for flexibility
export default {
  instanceSpec,
  createAsset: typeof createAsset !== 'undefined' ? createAsset : null
};
`
  
  return exportContent
}

/**
 * Export a batchable asset file (combined spec + code)
 * @param {string} code - The createAsset function code
 * @param {Object} options - Export options
 * @param {string} filename - Base filename
 */
export async function exportAsBatchableAsset(code, options = {}, filename = 'asset') {
  try {
    const content = await generateBatchableExport(code, options)
    const blob = new Blob([content], { type: 'text/javascript' })
    const url = URL.createObjectURL(blob)
    
    const link = document.createElement('a')
    link.href = url
    link.download = `${filename}.batchable.js`
    link.click()
    
    URL.revokeObjectURL(url)
    
    return { success: true }
  } catch (error) {
    console.error('[Exporter] Failed to generate batchable export:', error)
    return { success: false, error: error.message }
  }
}
